    def match(self, path_pattern: str):
        '''
        Match corresponding concrete paths that match the given path_pattern

        Paramaters
        path_pattern: string generated by CreatePathPattern in semantics_cypher.py that describes path to match

        Return
        A new Graph object with identical nodes and edges, an updated variable map, and updated concrete paths

        Failure results in a Graph object returned with empty variable map and paths
        '''

        path = [tuple(x.strip('()').split(',')) for x in path_pattern.split(':')]
        vars, paths = self.vars.copy(), self.paths.copy()
        for i in range(len(path)):
            for j in range(i, len(path)):
                if path[i][0] == path[j][0] and path[i][1] != path[j][1]:
                    return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])
                
        if len(path) == 1:
            (var_name, label) = path[0]

            # new variable means we have to cartesian with all nodes of that label
            if var_name not in vars:
                search_nodes = [x for x in self.nodes if label == x.get_property('label')]
                
                if search_nodes == []:
                    return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])

                new_paths = [(node,) for node in search_nodes] if len(paths) == 0 else [x + (node,) for x in self.paths for node in search_nodes]
                vars[var_name] = (len(new_paths[0]) - 1, label) # (idx of the variable on the path?, label)
                return Graph(nodes=self.nodes, edges=self.edges, var_map=vars, paths=new_paths)
            else:
                return Graph(nodes=self.nodes, edges=self.edges, var_map=vars, paths=paths)

        # if the pattern is longer than 1 node, then delegate to the create_table function to build out matching paths
        (paths, vars) = self.create_table('', path, paths, vars)
        return Graph(nodes=self.nodes, edges=self.edges, var_map=vars, paths=paths)
    
    def matchr(self, path_pattern):
        '''
        Recursive match corresponds to all of the matches after the first

        Parameters
        path_pattern: string generated by CreatePathPattern in semantics_cypher.py that describes path to match

        Return
        A new Graph object with identical nodes and edges, an updated variable map, and updated concrete paths

        Failure results in a Graph object returned with empty variable map and paths
        '''

        path = [tuple(x.strip('()').split(',')) for x in path_pattern.split(':')]

        if len(self.paths) == 0:
            return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])

        # ensure that at variables in new path are not completely disjoint with existing variables
        new_path_vars, existing_vars = set([x[0] for x in path]), set(self.vars.keys())

        if new_path_vars.isdisjoint(existing_vars):
            return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])

        # make sure labels agree for shared variables 
        for var in path:
            if var[0] in self.vars and var[1] != self.vars[var[0]][1]:
                return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])

        # generate tables for each of the match clauses
        previous_path, previous_vars = self.paths, self.vars
        new_paths, new_vars = self.create_table('', path, [], {})

        shared_variables = new_path_vars.intersection(previous_vars)
        different_variables = new_path_vars - existing_vars
       
        # cartesian the new and old paths, filtering on equality of shared variables
        final_paths = []
        for old_path in previous_path:
            for new_path in new_paths:
                valid_pair = True

                # if not equal on all shared variables, then we don't include that path
                for shared_variable in shared_variables:
                    (new_path_index, _), (old_path_index, _) = new_vars[shared_variable], previous_vars[shared_variable]

                    if old_path[old_path_index] != new_path[new_path_index]:
                        valid_pair = False
                        break
            
                # if they agree on all shared variables, then we merge our var_map and create extended paths
                if valid_pair:
                    temp = old_path
                    for different_var in different_variables:
                        new_path_index, new_path_label = new_vars[different_var]
                        temp = temp + (new_path[new_path_index],)
                        previous_vars[different_var] = len(temp) - 1, new_path_label

                    final_paths.append(temp)

        return Graph(nodes=self.nodes, edges=self.edges, var_map=previous_vars, paths=final_paths)
    
    def filter(self, predicate):
        '''
        Filters existing paths based on the predicate given

        Paramaters
        predicate: string generated by combination of operations definied in semantics_cypher.py

        Return
        A new graph object with the filtered paths

        Failure results in a Graph object returned with empty variable map and paths
        '''
        
        try:
            parsed = self.parse_expression(predicate)
        except ValueError:
            return Graph(nodes=self.nodes, edges=self.edges, var_map=self.vars, paths=[])
        
        # attempt to construct a boolean bit_vector representing whether each concrete path satisfies the predicate 
        try:
            bit_vector = self.evaluate_expression_on_paths(parsed, self.paths)
        except ValueError:
            return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])
        
        # filter out paths that do no satisfy predicate
        new_paths = [path for path, pred in zip(self.paths, bit_vector) if pred]
        return Graph(nodes=self.nodes, edges=self.edges, var_map=self.vars, paths=new_paths)
    
    def ret(self, list_of_properties):
        '''
        Return graph function that takes current paths and returns given properties

        Parameteres
        list_of_properties: string genereated by the CreateExpressionList function in semantics_cypher.py

        Return
        A new graph object with empty paths and output_graph representing the output of the query

        Failure results in a Graph object returned with empty paths and output_graph        
        '''
        
        properties = list_of_properties.split(':')
        try:
            parsed_properties = [self.parse_expression(p) for p in properties]
        except:
            return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])
            
         # duplicate properties causes it to fail
         # TODO: May need to change this, no need to decide failure in this case
        if len(parsed_properties) != len(set(parsed_properties)):
            return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[])
        
        
        output_graph, table = self.construct_return_graph(parsed_properties)
        return Graph(nodes=self.nodes, edges=self.edges, var_map={}, paths=[], output_graph=output_graph, table=table)
    
    # GRAPH UTIL FUNCTIONS
    def create_table(self, last_node_var, pattern_list, paths, vars):
        '''
        Helper function called in match and matchr that recursively builds out list of matching paths

        Parameters
        last_node_var: string given as the last variable used in the path. Default is '' for the first call
        pattern_list: list of parsed node/edge patterns to match
        paths: list of CypherType tuples representing already matches concrete paths
        vars: dictionary mapping variables names to indices in the path

        Return
        (paths, vars) tuple of updated paths and variable map
        '''
        
        # base case of pattern exhausted
        if len(pattern_list) == 0:
            return paths, vars

        # initial call has last_node_var as '' and we need to build the first node
        if last_node_var == '':
            (var_name, label) = pattern_list[0]

            if var_name not in vars:
                search_nodes = [x for x in self.nodes if label == x.get_property('label')]
                paths = [(node,) for node in search_nodes]
                vars[var_name] = (0, label)

            return self.create_table(var_name, pattern_list[1:], paths, vars)
        
        # no concrete paths match the pattern so return empty
        if len(paths) == 0:
            return (paths, {})
        
        # unpack our next edge and node from the pattern
        (edge_var, edge_type, edge_direction), (node_var, node_label) = pattern_list[0], pattern_list[1]
        
        # each edge must be distinct so if we have already used edge_var then it cannot be used again. Exit here
        if edge_var in vars:
            return self.create_table(node_var, pattern_list, [], vars)
        
        new_paths = []

        # handle loops
        if last_node_var == node_var:
            search_edges = [x for x in self.edges if edge_type == x.get_property('label')]
            node_index, _ = vars[last_node_var]

            for path in paths:
                node = path[node_index]
                for edge in search_edges:
                    if edge.get_property('start') == node.get_property('element_id') and edge.get_property('end') == node.get_property('element_id') and edge not in path:
                        new_paths.append(path + (edge,))
                        vars[edge_var] = (len(path), edge_type)
        else:
            search_edges = [x for x in self.edges if x.get_property('label') == edge_type]
            
            if node_var not in vars:
                search_nodes = [node for node in self.nodes if node_label == node.get_property('label')]
                
                last_node_index, _ = vars[last_node_var]
                for path in paths:
                    last_node = path[last_node_index]
                    for other_node in search_nodes:
                        for edge in search_edges:
                            # generalizing in this condition based off of which way the direction is
                            if (edge_direction == '<-' and edge.get_property('end') == last_node.get_property('element_id') and edge.get_property('start') == other_node.get_property('element_id') and edge not in path) or\
                                (edge_direction == '->' and edge.get_property('start') == last_node.get_property('element_id') and edge.get_property('end') == other_node.get_property('element_id') and edge not in path):
                                    new_paths.append(path + (edge,other_node))
                                    vars[edge_var] = (len(path), edge_type)
                                    vars[node_var] = (len(path) + 1, node_label)
            else:
                # node variable is bound so we only have to check edges that connect nodes already bound in our pathseBer
                (start_index, _), (end_index, _) = vars[node_var], vars[last_node_var]

                # if our edge is going left to right then we need to change our start/end nodes, so just swap the indices
                if edge_direction == '->':
                    start_index,end_index = end_index,start_index

                for path in paths:
                    start_node, end_node = path[start_index], path[end_index]
                    for edge in search_edges:
                        if edge.get_property('start') == start_node.get_property('element_id') and edge.get_property('end') == end_node.get_property('element_id') and edge not in path:
                            new_paths.append(path + (edge, start_node))
                            vars[edge_var] = (len(path), edge_type)
        return self.create_table(node_var, pattern_list[2:], new_paths, vars)
    
    
