class Graph(object):
    def __init__(self, nodes: set, edges: set, var_map: dict, paths: list, output_graph=[], 
                    table = []) -> None:
        '''
        Initialize values and create function maps
        
        Variables
        self.nodes: set of CypherType objects representing the nodes in the graph
        self.edges: set of CypherType objects representing the edges in the graph
        self.vars: dictionary mapping variable names to their corresponding index in the paths
        self.paths: list of tuples of CypherType objects representing a collection of concrete paths
        self.output_graph: list of CypherType objects representing the result of the query. Left empty until call to return
        self.table: values in table shape; For example, table as below is written as [[1, 4], [2, 5], [3, 6]]
        ----------
        1 | 2 | 3
        ----------
        4 | 5 | 6
        ----------

        Maps
        self.binary_operations: dictionary mapping function names to appropriate binary functions
        self.aggregators: dictionary mapping aggregation function names to appropriate aggregating functions
        '''

        self.nodes = nodes 
        self.edges = edges
        self.vars = var_map
        self.paths = paths
        self.output_graph = output_graph
        self.table = table

        self.binary_operations = {
            'add': gf.Addition(),
            'sub': gf.Subtraction(),
            'div': gf.Division(),
            'mul': gf.Multiplication(),
            'equal': lambda a,b: a == b,
            'ne': lambda a,b: a != b,
            'lt': lambda a,b: a < b,
            'lte': lambda a,b: a <= b,
            'and': lambda a,b: [(x and y) for x,y in zip(a,b)], 
            'or': lambda a,b: [(x or y) for x,y in zip(a,b)],
        }

        self.aggregators = {
            'COUNT': gf.Count(),
            'SUM': gf.Sum(),
            'MAX': gf.Max(),
            'MIN': gf.Min(),
            'AVG': gf.Avg()
        }
    

